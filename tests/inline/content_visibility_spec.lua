describe("auto visibility in a scroll column", function()
  it("rejects non-integral geometry and invalid canonical indices", function()
    local Visibility = require("fibrous.inline.visibility")
    assert.has_error(function()
      Visibility.new({ estimate = 1.5 })
    end)
    assert.has_error(function()
      Visibility.new({ gap = 0.5 })
    end)
    assert.has_error(function()
      Visibility.new({ overscan = 2.5 })
    end)
    local model = Visibility.new()
    assert.has_error(function() model:offset(-1) end)
    assert.has_error(function() model:offset(0.5) end)
    assert.has_error(function()
      model:measure(0, 1)
    end)
    assert.has_error(function()
      model:measure(1.5, 1)
    end)
    assert.has_error(function()
      model:measure(1, -1)
    end)
    assert.has_error(function()
      model:range(-1)
    end)
  end)

  it("indexes unvisited items by intrinsic height and remembers measured heights", function()
    local m = require("fibrous.inline.visibility").new({ estimate = 3, gap = 1 })
    m.count = 50000
    assert.equal(100000, m:offset(25000))
    m:measure(10, 9)
    assert.equal(100006, m:offset(25000))
    assert.equal(25001, m:item(100006))
    m:measure(10, 0)
    assert.equal(99996, m:offset(25000))
    assert.equal(11, m:item(m:offset(9)))
  end)
end)
